# make_results_tex.R  (edu-revision)
# ------------------------------------------------------------------
# Writes every number used in the Rasch results section as a LaTeX macro,
# plus the results table, so that no number is typed by hand.
# Run after analysis/rasch_fair_benchmark.R, from the repository root:
#   Rscript analysis/make_results_tex.R
# Outputs: latex/generated/rasch_numbers.tex, latex/generated/rasch_table.tex
# ------------------------------------------------------------------
d  <- file.path("data", "edu_revision")
mn <- read.csv(file.path(d, "r_rasch_arm_means.csv"),    stringsAsFactors = FALSE)
ct <- read.csv(file.path(d, "r_rasch_pfp_contrasts.csv"), stringsAsFactors = FALSE)
gs <- read.csv(file.path(d, "r_rasch_grid_summary.csv"), stringsAsFactors = FALSE)
st <- read.csv(file.path(d, "rasch_students.csv"),       stringsAsFactors = FALSE)
dir.create(file.path("latex", "generated"), showWarnings = FALSE, recursive = TRUE)

f3 <- function(x) sprintf("%.3f", x)
f2 <- function(x) sprintf("%.2f", x)
sg <- function(x) sprintf("%+.3f", x)
rn <- c(volkan = "One", difficulty = "Two")                 # macro suffix per rule
mname <- c(zpd = "Zpd", zpd_40_60 = "ZpdA", zpd_60_80 = "ZpdC", zpd_40_70 = "ZpdE",
           zpd_40_80 = "ZpdW", bored = "Bored", frustr = "Frustr", mean_p = "MeanP",
           gain = "Gain", track = "Track")
lines <- c("% Generated by analysis/make_results_tex.R -- do not edit by hand.")
def <- function(name, val) lines <<- c(lines, sprintf("\\newcommand{\\%s}{%s}", name, val))

def("RaschN", sum(st$rule == "volkan" & st$arm == "PFP"))
def("RaschT", 120)
for (i in seq_len(nrow(mn))) {
  r <- mn[i, ]; if (!r$metric %in% names(mname)) next
  base <- paste0("r", r$arm, mname[[r$metric]], rn[[r$rule]])
  def(base, f3(r$mean)); def(paste0(base, "Lo"), f3(r$ci_low)); def(paste0(base, "Hi"), f3(r$ci_high))
}
for (i in seq_len(nrow(ct))) {
  r <- ct[i, ]; if (!r$metric %in% names(mname)) next
  other <- sub("PFP - ", "", r$comparison)
  base <- paste0("c", other, mname[[r$metric]], rn[[r$rule]])
  def(base, sg(r$mean_diff)); def(paste0(base, "Lo"), sg(r$ci_low)); def(paste0(base, "Hi"), sg(r$ci_high))
  def(paste0(base, "Dz"), if (is.na(r$d_z)) "--" else sprintf("%+.2f", r$d_z))
}
# grid robustness
for (rule in names(rn)) {
  p <- gs[gs$rule == rule & gs$arm == "PFP", ]; c <- gs[gs$rule == rule & gs$arm == "CAT", ]
  def(paste0("gridPfpCells", rn[[rule]]), nrow(p))
  def(paste0("gridBestPfpZpd", rn[[rule]]), f3(max(p$zpd)))
  def(paste0("gridBestCatZpd", rn[[rule]]), f3(max(c$zpd)))
  def(paste0("gridBestPfpGain", rn[[rule]]), f3(max(p$gain)))
  def(paste0("gridBestCatGain", rn[[rule]]), f3(max(c$gain)))
  def(paste0("gridPfpBeatsCatGain", rn[[rule]]), sum(p$gain > max(c$gain)))
  def(paste0("gridPfpBeatsCatZpd", rn[[rule]]), sum(p$zpd > max(c$zpd)))
}
writeLines(lines, file.path("latex", "generated", "rasch_numbers.tex"))

# results table
arms <- c("Saturn", "Factory", "CAT", "PFP")
lab  <- c(Saturn = "Unconstrained (Saturn)", Factory = "Fixed sequence (Factory)",
          CAT = "Adaptive, $P^\\ast=0.70$ (CAT)", PFP = "PFP (\\texttt{Werredu})")
rows <- c("zpd_40_60", "zpd", "zpd_60_80", "zpd_40_70", "frustr", "bored", "mean_p", "gain", "track")
rlab <- c(zpd_40_60 = "Share $0.40 \\le P \\le 0.60$", zpd = "Share $0.50 \\le P \\le 0.70$ (pre-specified)",
          zpd_60_80 = "Share $0.60 \\le P \\le 0.80$", zpd_40_70 = "Share $0.40 \\le P \\le 0.70$ (post hoc)",
          frustr = "Share $P < 0.30$", bored = "Share $P > 0.85$", mean_p = "Mean $P$",
          gain = "Ability gain $\\theta_T - \\theta_0$", track = "Mean $|b_t - \\theta_t|$")
tab <- c("% Generated by analysis/make_results_tex.R -- do not edit by hand.",
         "\\begin{tabular}{l l r r r r}", "\\toprule",
         paste0("Rule & Outcome & ", paste(lab[arms], collapse = " & "), " \\\\"), "\\midrule")
for (rule in names(rn)) {
  first <- TRUE
  for (m in rows) {
    v <- sapply(arms, function(a) { x <- mn[mn$rule == rule & mn$arm == a & mn$metric == m, ]; f3(x$mean) })
    rl <- if (first) (if (rule == "volkan") "1: symmetric" else "2: difficulty-weighted") else ""
    tab <- c(tab, paste0(rl, " & ", rlab[[m]], " & ", paste(v, collapse = " & "), " \\\\"))
    first <- FALSE
  }
  if (rule == "volkan") tab <- c(tab, "\\midrule")
}
tab <- c(tab, "\\bottomrule", "\\end{tabular}")
writeLines(tab, file.path("latex", "generated", "rasch_table.tex"))
cat("written latex/generated/rasch_numbers.tex and rasch_table.tex\n")
